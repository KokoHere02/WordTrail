CREATE TABLE IF NOT EXISTS sentence_question (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 english_text VARCHAR(2000) NOT NULL,reference_translation VARCHAR(2000) NOT NULL,
 explanation VARCHAR(4000) NOT NULL,difficulty INT NOT NULL DEFAULT 1 CHECK(difficulty BETWEEN 1 AND 3),
 source VARCHAR(255) NOT NULL,source_reference VARCHAR(512),status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','INACTIVE')),
 version BIGINT NOT NULL DEFAULT 0,
 content_hash VARCHAR(64) GENERATED ALWAYS AS (LOWER(RAWTOHEX(HASH('SHA-256',STRINGTOUTF8(TRIM(english_text)))))) UNIQUE,
 CHECK(CHAR_LENGTH(TRIM(english_text))>0 AND CHAR_LENGTH(TRIM(reference_translation))>0 AND CHAR_LENGTH(TRIM(explanation))>0 AND CHAR_LENGTH(TRIM(source))>0)
);
CREATE TABLE IF NOT EXISTS sentence_word (
 sentence_id BIGINT NOT NULL REFERENCES sentence_question(id),word_id BIGINT NOT NULL REFERENCES word(id),PRIMARY KEY(sentence_id,word_id)
);
CREATE TABLE IF NOT EXISTS user_sentence_favorite (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES user_account(id),
 sentence_id BIGINT NOT NULL REFERENCES sentence_question(id),created_at TIMESTAMP(3) NOT NULL,UNIQUE(user_id,sentence_id)
);
CREATE TABLE IF NOT EXISTS sentence_translation_session (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES user_account(id),
 selection_source VARCHAR(20) NOT NULL CHECK(selection_source IN ('BANK','REVIEW','FAVORITES','DUE')),
 status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',created_at TIMESTAMP(3) NOT NULL,completed_at TIMESTAMP(3),UNIQUE(id,user_id),
 CHECK((status='IN_PROGRESS' AND completed_at IS NULL) OR (status='COMPLETED' AND completed_at IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS sentence_translation_item (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,session_id BIGINT NOT NULL REFERENCES sentence_translation_session(id),
 sentence_id BIGINT NOT NULL REFERENCES sentence_question(id),sort_order INT NOT NULL CHECK(sort_order BETWEEN 1 AND 50),
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','AWAITING_REVIEW','DONE')),
 english_text VARCHAR(2000) NOT NULL,reference_translation VARCHAR(2000) NOT NULL,explanation VARCHAR(4000) NOT NULL,
 difficulty INT NOT NULL CHECK(difficulty BETWEEN 1 AND 3),source VARCHAR(255) NOT NULL,source_reference VARCHAR(512),
 CHECK(CHAR_LENGTH(TRIM(english_text))>0 AND CHAR_LENGTH(TRIM(reference_translation))>0 AND CHAR_LENGTH(TRIM(explanation))>0 AND CHAR_LENGTH(TRIM(source))>0),
 UNIQUE(session_id,sentence_id),UNIQUE(session_id,sort_order),UNIQUE(id,session_id,sentence_id)
);
CREATE TABLE IF NOT EXISTS sentence_translation_attempt (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT NOT NULL,session_id BIGINT NOT NULL,item_id BIGINT NOT NULL,sentence_id BIGINT NOT NULL,
 submit_request_id VARCHAR(64) NOT NULL,action VARCHAR(20) NOT NULL,translation VARCHAR(2000),learning_date DATE NOT NULL,submitted_at TIMESTAMP(3) NOT NULL,
 self_assessment VARCHAR(20),review_request_id VARCHAR(64),review_date DATE,reviewed_at TIMESTAMP(3),
 UNIQUE(item_id),UNIQUE(user_id,submit_request_id),UNIQUE(user_id,review_request_id),UNIQUE(id,user_id,sentence_id),
 FOREIGN KEY(session_id,user_id) REFERENCES sentence_translation_session(id,user_id),
 FOREIGN KEY(item_id,session_id,sentence_id) REFERENCES sentence_translation_item(id,session_id,sentence_id),
 CHECK((action='ANSWER' AND translation IS NOT NULL AND CHAR_LENGTH(TRIM(translation))>0) OR (action='REVEAL' AND translation IS NULL)),
 CHECK((self_assessment IS NULL AND review_request_id IS NULL AND review_date IS NULL AND reviewed_at IS NULL)
   OR (self_assessment IS NOT NULL AND self_assessment IN ('UNDERSTOOD','PARTIAL','NOT_UNDERSTOOD') AND review_request_id IS NOT NULL
     AND review_date IS NOT NULL AND reviewed_at IS NOT NULL AND reviewed_at>=submitted_at))
);
CREATE TABLE IF NOT EXISTS user_sentence_review_state (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES user_account(id),
 sentence_id BIGINT NOT NULL REFERENCES sentence_question(id),last_attempt_id BIGINT NOT NULL REFERENCES sentence_translation_attempt(id),
 review_level INT NOT NULL CHECK(review_level BETWEEN 0 AND 5),last_assessment VARCHAR(20) NOT NULL CHECK(last_assessment IN ('UNDERSTOOD','PARTIAL','NOT_UNDERSTOOD')),
 reviewed_at TIMESTAMP(3) NOT NULL,next_review_date DATE NOT NULL CHECK(next_review_date>CAST(reviewed_at AS DATE)),UNIQUE(user_id,sentence_id)
);
CREATE TABLE IF NOT EXISTS sentence_import_batch (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES user_account(id),request_id VARCHAR(64) NOT NULL,
 content_hash VARCHAR(64) NOT NULL,row_count INT NOT NULL CHECK(row_count BETWEEN 1 AND 100),created_at TIMESTAMP(3) NOT NULL,UNIQUE(user_id,request_id)
);
CREATE TABLE IF NOT EXISTS sentence_import_item (
 batch_id BIGINT NOT NULL REFERENCES sentence_import_batch(id),csv_row_number INT NOT NULL,sentence_id BIGINT NOT NULL REFERENCES sentence_question(id),
 PRIMARY KEY(batch_id,csv_row_number),UNIQUE(sentence_id)
);
CREATE TABLE IF NOT EXISTS sentence_item_word (
 item_id BIGINT NOT NULL REFERENCES sentence_translation_item(id),word_id BIGINT NOT NULL,word VARCHAR(255) NOT NULL,PRIMARY KEY(item_id,word_id)
);
CREATE TABLE IF NOT EXISTS user_sentence_note (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES user_account(id),sentence_id BIGINT NOT NULL REFERENCES sentence_question(id),
 content VARCHAR(4000) NOT NULL,attempt_id BIGINT,version BIGINT NOT NULL CHECK(version>=1),updated_at TIMESTAMP(3) NOT NULL,
 UNIQUE(user_id,sentence_id),FOREIGN KEY(attempt_id,user_id,sentence_id) REFERENCES sentence_translation_attempt(id,user_id,sentence_id)
);
CREATE TABLE IF NOT EXISTS user_sentence_note_tag (
 note_id BIGINT NOT NULL REFERENCES user_sentence_note(id),error_tag VARCHAR(20) NOT NULL CHECK(error_tag IN ('VOCABULARY','TENSE','NEGATION','STRUCTURE','OTHER')),
 PRIMARY KEY(note_id,error_tag)
);
