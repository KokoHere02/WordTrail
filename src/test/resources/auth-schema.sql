-- Test-only approximation of the existing MySQL user_account table.
-- VARCHAR_IGNORECASE models utf8mb4_0900_ai_ci for the permitted ASCII usernames.
CREATE TABLE IF NOT EXISTS user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR_IGNORECASE(64) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    nickname VARCHAR(64),
    auth_version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_username UNIQUE (username)
);

CREATE TABLE IF NOT EXISTS user_auth_session (
    id VARCHAR(32) PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES user_account(id),device_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,last_refreshed_at TIMESTAMP(6) NOT NULL,expires_at TIMESTAMP(6) NOT NULL,revoked_at TIMESTAMP(6),
    UNIQUE(id,user_id),CHECK(expires_at>created_at AND last_refreshed_at>=created_at)
);
CREATE TABLE IF NOT EXISTS refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    session_id VARCHAR(32),
    token_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    revoked_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash),
    FOREIGN KEY(session_id,user_id) REFERENCES user_auth_session(id,user_id),
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES user_account(id)
);

CREATE TABLE IF NOT EXISTS user_learning_setting (
    user_id BIGINT PRIMARY KEY REFERENCES user_account(id),
    daily_target INT NOT NULL DEFAULT 20 CHECK (daily_target BETWEEN 1 AND 200),
    preferred_study_mode VARCHAR(20) NOT NULL DEFAULT 'RECOGNITION' CHECK(preferred_study_mode IN ('RECOGNITION','DICTATION','FOLLOW_TYPING','LISTEN_DICTATION')),
    new_word_target INT,review_limit INT,
    audio_auto_play BOOLEAN NOT NULL DEFAULT FALSE,audio_accent VARCHAR(2) NOT NULL DEFAULT 'US',
    audio_playback_rate DECIMAL(3,2) NOT NULL DEFAULT 1.00,audio_repeat_count INT NOT NULL DEFAULT 1,
    CHECK((new_word_target IS NULL AND review_limit IS NULL) OR (new_word_target IS NOT NULL AND review_limit IS NOT NULL
      AND new_word_target BETWEEN 0 AND 200 AND review_limit BETWEEN 0 AND 200 AND new_word_target+review_limit=daily_target)),
    CHECK(audio_accent IN ('US','UK') AND audio_playback_rate BETWEEN 0.50 AND 1.50 AND audio_repeat_count BETWEEN 1 AND 5),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS word (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word VARCHAR(255) NOT NULL,
    phonetic VARCHAR(255), translation TEXT, definition TEXT,
    pos VARCHAR(255), tag VARCHAR(255), bnc BIGINT, frq BIGINT, exchange TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS word_book (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL, description TEXT, owner_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS word_book_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES word_book(id),
    word_id BIGINT NOT NULL REFERENCES word(id),
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (book_id, word_id)
);
CREATE TABLE IF NOT EXISTS learning_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_account(id),
    book_id BIGINT REFERENCES word_book(id),
    selection_type VARCHAR(20) NOT NULL CHECK (selection_type IN ('BOOK', 'MANUAL', 'DAILY')),
    task_type VARCHAR(20) NOT NULL DEFAULT 'PRACTICE' CHECK (task_type IN ('PRACTICE', 'DAILY')),
    practice_mode VARCHAR(20) NOT NULL DEFAULT 'RECOGNITION',
    learning_date DATE, daily_target INT,
    study_mode VARCHAR(20) NOT NULL DEFAULT 'RECOGNITION' CHECK(study_mode IN ('RECOGNITION','DICTATION','FOLLOW_TYPING','LISTEN_DICTATION')),
    new_word_target INT,review_limit INT,creation_request_id VARCHAR(64),creation_fingerprint CHAR(64),consolidation_reason VARCHAR(30),follow_typing_target INT,
    UNIQUE(user_id,creation_request_id),
    CHECK((new_word_target IS NULL AND review_limit IS NULL) OR (task_type='DAILY' AND new_word_target IS NOT NULL AND review_limit IS NOT NULL
      AND new_word_target BETWEEN 0 AND 200 AND review_limit BETWEEN 0 AND 200 AND new_word_target+review_limit=daily_target)),
    CHECK((practice_mode IN ('CONSOLIDATION','FOLLOW_TYPING') AND creation_request_id IS NOT NULL AND creation_fingerprint IS NOT NULL)
      OR (practice_mode NOT IN ('CONSOLIDATION','FOLLOW_TYPING') AND creation_request_id IS NULL AND creation_fingerprint IS NULL AND consolidation_reason IS NULL)),
    CHECK((practice_mode='FOLLOW_TYPING' AND follow_typing_target IS NOT NULL AND follow_typing_target BETWEEN 10 AND 20
      AND study_mode='FOLLOW_TYPING' AND mode_version=0 AND book_id IS NULL AND consolidation_reason IS NULL)
      OR (practice_mode<>'FOLLOW_TYPING' AND follow_typing_target IS NULL)),
    CHECK(consolidation_reason IS NULL OR consolidation_reason IN ('SPELLING_ERROR','ANSWER_REVEALED','UNRECOGNIZED','ATTEMPT_LIMIT','PENDING_VERIFICATION')),
    mode_version BIGINT NOT NULL DEFAULT 0 CHECK(mode_version>=0),
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS' CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'ABANDONED')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,
    UNIQUE (user_id, task_type, learning_date),
    CHECK (practice_mode='RECOGNITION' OR (practice_mode IN ('DICTATION','CONSOLIDATION','FOLLOW_TYPING') AND task_type='PRACTICE' AND selection_type='MANUAL')),
    CHECK ((task_type='DAILY' AND selection_type='DAILY' AND learning_date IS NOT NULL AND daily_target>0)
        OR (task_type='PRACTICE' AND selection_type IN ('BOOK','MANUAL') AND learning_date IS NULL AND daily_target IS NULL))
);
CREATE TABLE IF NOT EXISTS learning_batch_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES learning_batch(id),
    word_id BIGINT NOT NULL REFERENCES word(id),
    sort_order INT NOT NULL CHECK (sort_order >= 1),
    result INT CHECK (result IS NULL OR result IN (1, 2, 3)), answered_at TIMESTAMP,
    item_type VARCHAR(20) CHECK (item_type IS NULL OR item_type IN ('NEW','REVIEW')),
    learning_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (learning_status IN ('PENDING','RELEARNING','DONE','SKIPPED')),
    queue_order BIGINT NOT NULL DEFAULT 0,
    answer_count INT NOT NULL DEFAULT 0, relearn_count INT NOT NULL DEFAULT 0,
    completed_at TIMESTAMP,
    status_before_skip VARCHAR(20) CHECK (status_before_skip IS NULL OR status_before_skip IN ('PENDING','RELEARNING','DONE')),
    skipped_at TIMESTAMP,
    reinforcement_remaining INT CHECK (reinforcement_remaining IS NULL OR reinforcement_remaining BETWEEN 0 AND 3),
    completion_reason VARCHAR(20) CHECK (completion_reason IS NULL OR completion_reason IN ('RECALLED','LIMIT_REACHED','FOLLOW_TYPED','ASSISTED')),
    study_word VARCHAR(255),study_translation TEXT,study_phonetic VARCHAR(255),
    study_hint_used BOOLEAN NOT NULL DEFAULT FALSE,study_attempt_count INT NOT NULL DEFAULT 0 CHECK(study_attempt_count>=0),
    study_presentation_id VARCHAR(36),study_presentation_version BIGINT,study_extra_training BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK((study_presentation_id IS NULL AND study_presentation_version IS NULL) OR (study_presentation_id IS NOT NULL AND study_presentation_version IS NOT NULL)),
    dictation_target VARCHAR(255),dictation_translation TEXT,
    dictation_had_failure BOOLEAN,dictation_correct_streak INT CHECK(dictation_correct_streak BETWEEN 0 AND 2),
    dictation_presentation_id VARCHAR(36),
    CHECK ((dictation_target IS NULL AND dictation_translation IS NULL AND dictation_had_failure IS NULL AND dictation_correct_streak IS NULL AND dictation_presentation_id IS NULL)
      OR (dictation_target IS NOT NULL AND dictation_translation IS NOT NULL AND dictation_had_failure IS NOT NULL AND dictation_correct_streak IS NOT NULL AND result IS NULL)),
    UNIQUE (batch_id, word_id), UNIQUE (batch_id, sort_order),
    CHECK ((learning_status='SKIPPED' AND status_before_skip IS NOT NULL AND skipped_at IS NOT NULL)
        OR (learning_status<>'SKIPPED' AND status_before_skip IS NULL AND skipped_at IS NULL))
);
CREATE TABLE IF NOT EXISTS user_word_state (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_account(id),
    word_id BIGINT NOT NULL REFERENCES word(id),
    last_result INT CHECK (last_result IN (1, 2, 3)),
    last_batch_item_id BIGINT REFERENCES learning_batch_item(id),
    first_learned_at TIMESTAMP, last_learned_at TIMESTAMP,
    plan_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (plan_status IN ('ACTIVE','PAUSED','REMOVED')),
    joined_at TIMESTAMP NOT NULL,
    next_review_at TIMESTAMP, review_level INT NOT NULL DEFAULT 0 CHECK (review_level BETWEEN 0 AND 6),
    UNIQUE (user_id, word_id)
);

CREATE TABLE IF NOT EXISTS word_review_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_mode VARCHAR(20) NOT NULL DEFAULT 'RECOGNITION' CHECK(feedback_mode IN ('RECOGNITION','DICTATION','FOLLOW_TYPING','LISTEN_DICTATION')),
    user_id BIGINT NOT NULL REFERENCES user_account(id), word_id BIGINT NOT NULL REFERENCES word(id),
    batch_id BIGINT NOT NULL REFERENCES learning_batch(id), batch_item_id BIGINT NOT NULL REFERENCES learning_batch_item(id),
    request_id VARCHAR(64) NOT NULL, event_type VARCHAR(20) NOT NULL DEFAULT 'ANSWER',
    corrects_log_id BIGINT REFERENCES word_review_log(id), learning_date DATE NOT NULL,
    result INT NOT NULL CHECK (result IN (1,2,3)), attempt_no INT NOT NULL CHECK (attempt_no>=1),
    affects_schedule BOOLEAN NOT NULL DEFAULT FALSE,
    schedule_before VARCHAR(4000), schedule_after VARCHAR(4000),
    answered_at TIMESTAMP(3) NOT NULL, created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id,request_id),
    CHECK ((event_type='ANSWER' AND corrects_log_id IS NULL) OR (event_type='CORRECTION' AND corrects_log_id IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS dictation_review_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_account(id),word_id BIGINT NOT NULL REFERENCES word(id),
    batch_id BIGINT NOT NULL REFERENCES learning_batch(id),batch_item_id BIGINT NOT NULL REFERENCES learning_batch_item(id),
    request_id VARCHAR(64) NOT NULL,presentation_id VARCHAR(36) NOT NULL,event_type VARCHAR(20) NOT NULL,
    input_text VARCHAR(255),verdict VARCHAR(20) NOT NULL,attempt_no INT NOT NULL CHECK(attempt_no BETWEEN 1 AND 6),
    learning_date DATE NOT NULL,answered_at TIMESTAMP(3) NOT NULL,
    correct_streak_before INT NOT NULL CHECK(correct_streak_before BETWEEN 0 AND 2),
    correct_streak_after INT NOT NULL CHECK(correct_streak_after BETWEEN 0 AND 2),had_failure_after BOOLEAN NOT NULL,
    item_status_after VARCHAR(20) NOT NULL,completion_reason_after VARCHAR(20),affects_schedule BOOLEAN NOT NULL DEFAULT FALSE CHECK(affects_schedule=FALSE),
    UNIQUE(user_id,request_id),UNIQUE(batch_item_id,attempt_no),UNIQUE(user_id,presentation_id),
    CHECK((event_type='ANSWER' AND input_text IS NOT NULL AND verdict IN ('CORRECT','INCORRECT')) OR (event_type='REVEAL' AND input_text IS NULL AND verdict='REVEALED')),
    CHECK((item_status_after='RELEARNING' AND completion_reason_after IS NULL) OR (item_status_after='DONE' AND completion_reason_after IS NOT NULL AND completion_reason_after IN ('RECALLED','LIMIT_REACHED')))
);

CREATE TABLE IF NOT EXISTS word_training_attempt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_account(id),word_id BIGINT NOT NULL REFERENCES word(id),
    batch_id BIGINT NOT NULL REFERENCES learning_batch(id),batch_item_id BIGINT NOT NULL REFERENCES learning_batch_item(id),
    request_id VARCHAR(64) NOT NULL,presentation_id VARCHAR(36) NOT NULL,mode_version BIGINT NOT NULL CHECK(mode_version>=0),
    mode VARCHAR(20) NOT NULL CHECK(mode IN ('RECOGNITION','DICTATION','FOLLOW_TYPING','LISTEN_DICTATION')),
    action VARCHAR(20) NOT NULL,input_text VARCHAR(255),self_assessment INT,verdict VARCHAR(20) NOT NULL,
    hint_used BOOLEAN NOT NULL,extra_training BOOLEAN NOT NULL,attempt_no INT NOT NULL CHECK(attempt_no>0),
    review_log_id BIGINT REFERENCES word_review_log(id),learning_date DATE NOT NULL,answered_at TIMESTAMP NOT NULL,
    UNIQUE(user_id,request_id),UNIQUE(user_id,presentation_id),UNIQUE(batch_item_id,attempt_no),UNIQUE(review_log_id),
    CHECK((action='REVEAL' AND input_text IS NULL AND self_assessment IS NULL AND verdict='REVEALED' AND hint_used=TRUE AND review_log_id IS NULL)
      OR (action='ANSWER' AND ((mode='RECOGNITION' AND input_text IS NULL AND self_assessment IS NOT NULL AND self_assessment IN (1,2,3) AND verdict='SELF_ASSESSED')
        OR (mode IN ('DICTATION','FOLLOW_TYPING','LISTEN_DICTATION') AND input_text IS NOT NULL AND self_assessment IS NULL AND verdict IN ('CORRECT','INCORRECT'))))),
    CHECK(extra_training=FALSE OR review_log_id IS NULL)
);
